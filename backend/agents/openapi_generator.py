"""Reverse-Engineered OpenAPI 3.1.0 Specification Generator."""

import json
from typing import Any

import yaml

from backend.graph.knowledge_graph import KnowledgeGraph


class OpenAPISpecGenerator:
    """Generates an OpenAPI 3.1.0 specification document directly from the discovered Knowledge Graph."""

    def __init__(self, knowledge_graph: KnowledgeGraph) -> None:
        self.kg = knowledge_graph

    def generate_spec(
        self,
        title: str = "Discovered Travel API",
        version: str = "1.0.0",
        base_url: str = "http://127.0.0.1:8000",
    ) -> dict[str, Any]:
        """Construct full OpenAPI 3.1 document structure from graph topology."""
        spec: dict[str, Any] = {
            "openapi": "3.1.0",
            "info": {
                "title": title,
                "version": version,
                "description": "Reverse-engineered API specification generated by TRIPWIRE autonomous recon.",
            },
            "servers": [{"url": base_url, "description": "Target Host"}],
            "paths": {},
            "components": {
                "securitySchemes": {
                    "BearerAuth": {
                        "type": "http",
                        "scheme": "bearer",
                        "bearerFormat": "JWT",
                    }
                },
                "schemas": {},
            },
        }

        endpoints = self.kg.get_endpoints()

        for ep in endpoints:
            method_lower = ep["method"].lower()
            path = ep["path"]
            auth_required = ep.get("auth_required", False)

            if path not in spec["paths"]:
                spec["paths"][path] = {}

            # Infer tag from root path segment
            segments = [s for s in path.split("/") if s and not s.startswith("{")]
            tag = segments[1] if len(segments) > 1 else (segments[0] if segments else "default")

            # Collect parameters from graph
            ep_params = self.kg.get_parameters_for_endpoint(ep["endpoint_id"])
            open_api_params: list[dict[str, Any]] = []

            for param in ep_params:
                p_loc = param.get("location", "query")
                if p_loc in {"query", "path", "header"}:
                    open_api_params.append(
                        {
                            "name": param["name"],
                            "in": p_loc,
                            "required": p_loc == "path",
                            "schema": {"type": param.get("param_type", "string")},
                        }
                    )

            operation: dict[str, Any] = {
                "tags": [tag],
                "summary": f"{ep['method']} {path}",
                "description": f"Autonomously discovered {ep['method']} endpoint at {path}.",
                "parameters": open_api_params,
                "responses": {
                    "200": {
                        "description": "Successful operation",
                        "content": {"application/json": {"schema": {"type": "object"}}},
                    },
                    "400": {"description": "Bad Request"},
                },
            }

            if auth_required:
                operation["security"] = [{"BearerAuth": []}]
                operation["responses"]["401"] = {"description": "Unauthorized"}
                operation["responses"]["403"] = {"description": "Forbidden"}

            # Add requestBody for mutation methods
            if method_lower in {"post", "put", "patch"}:
                body_params = [p for p in ep_params if p.get("location") == "body"]
                properties: dict[str, Any] = {}
                for bp in body_params:
                    properties[bp["name"]] = {"type": bp.get("param_type", "string")}

                operation["requestBody"] = {
                    "required": True,
                    "content": {
                        "application/json": {
                            "schema": {
                                "type": "object",
                                "properties": properties or {"example_field": {"type": "string"}},
                            }
                        }
                    },
                }

            spec["paths"][path][method_lower] = operation

        return spec

    def export_yaml(self, **kwargs: Any) -> str:
        """Export generated spec as formatted YAML."""
        spec = self.generate_spec(**kwargs)
        return yaml.dump(spec, sort_keys=False)

    def export_json(self, **kwargs: Any) -> str:
        """Export generated spec as formatted JSON."""
        spec = self.generate_spec(**kwargs)
        return json.dumps(spec, indent=2)
