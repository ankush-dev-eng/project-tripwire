def get_vulnerabilities(split: str | None = None) -> list[PlantedVulnerability]:
    """Retrieve planted vulnerabilities filtered by split ('dev' or 'held_out')."""
    if split is None:
        return PLANTED_VULNERABILITIES
    return [v for v in PLANTED_VULNERABILITIES if v.split == split]
